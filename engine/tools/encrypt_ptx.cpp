// Build-time tool: encrypt_ptx
// Usage: encrypt_ptx <input.ptx> <output.h> <array_name>
// Reads a PTX file, AES-256-CTR encrypts it, writes a C++ header with
// the encrypted bytes as a uint8_t[] array ready to embed in the binary.
//
// Run during CMake build (add_custom_command) BEFORE compiling the engine.
// The generated header is #included by NvrtcCompiler.cpp.

#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>
#include <fstream>
#include <iterator>
#include <ctime>

// Include the same AES implementation used at runtime
#include "../src/protect/Aes256.h"
#include "../src/protect/PtxCrypt.h"

int main(int argc, char* argv[]) {
    if (argc < 4) {
        std::fprintf(stderr, "Usage: encrypt_ptx <input.ptx> <output.h> <array_name>\n");
        return 1;
    }

    const char* inPath   = argv[1];
    const char* outPath  = argv[2];
    const char* arrName  = argv[3];

    // Read PTX file
    std::ifstream in(inPath, std::ios::binary);
    if (!in) { std::fprintf(stderr, "Cannot open: %s\n", inPath); return 1; }
    std::string ptx((std::istreambuf_iterator<char>(in)),
                     std::istreambuf_iterator<char>());

    // Encrypt
    auto encrypted = symm::protect::PtxCrypt::encrypt(ptx);

    // Write C++ header
    std::ofstream out(outPath);
    if (!out) { std::fprintf(stderr, "Cannot write: %s\n", outPath); return 1; }

    out << "// AUTO-GENERATED by encrypt_ptx — DO NOT EDIT\n";
    out << "// Source: " << inPath << "\n";
    out << "// Original size: " << ptx.size() << " bytes\n";
    out << "// Encrypted size: " << encrypted.size() << " bytes\n";
    out << "// Key: SYMM_PTX_KEY (compile-time define)\n\n";
    out << "#pragma once\n";
    out << "#include <cstdint>\n\n";
    out << "static const uint8_t " << arrName << "[] = {\n    ";

    for (size_t i = 0; i < encrypted.size(); i++) {
        out << "0x" << std::hex;
        out.width(2); out.fill('0');
        out << (int)encrypted[i];
        if (i + 1 < encrypted.size()) out << ",";
        if ((i + 1) % 16 == 0) out << "\n    ";
        else out << " ";
    }

    out << "\n};\n\n";
    out << "static const size_t " << arrName << "_size = " << std::dec << encrypted.size() << ";\n";

    std::printf("encrypt_ptx: %s → %s (%zu bytes encrypted)\n",
                inPath, outPath, encrypted.size());
    return 0;
}
